#!/usr/bin/env bash
#
# Stop the region's bastion instance.
#
# The bastion is only useful while you are on an SSM session (or while it is
# acting as a Tailscale subnet router), so stopping it between uses drops the
# recurring cost to just the EBS root volume. The instance, its id, its security
# group and its SSM parameter all survive — `bastion-start.sh` brings the same
# box back.
#
#   ./scripts/bastion-stop.sh ap-southeast-2
#   ./scripts/bastion-stop.sh ap-southeast-2 --no-wait
#
# By default it polls until the instance reaches 'stopped', so a successful exit
# means billing for the instance has actually ceased. `--no-wait` returns as
# soon as the stop is accepted.
#
# The region defaults to ap-southeast-2 when omitted. Note that this differs
# from the `cdk` commands in this repo, which never default: the bastion's SSM
# parameter name is identical in every region, so an omitted region here stops
# ap-southeast-2's box rather than erroring. The script says so on stderr
# whenever it falls back.
#
# Note: the instance's auto-assigned public IPv4 is released on stop and a new
# one is assigned on start. Nothing here depends on it (SSM and Tailscale are
# both outbound-initiated), but do not pin anything to that address.
#
# Requires: aws CLI v2.
set -euo pipefail

# Published by BastionStack — see lib/bastion-stack.ts ('ssmParam', key
# 'instance-id'). Generated by derrops-conventions; mirrored here because a
# shell script cannot call the library.
readonly PARAM_NAME='/derrops/region/bastion/instance-id'

# Region used when the caller omits one.
readonly DEFAULT_REGION='ap-southeast-2'

usage() {
  cat <<'EOF'
Usage: bastion-stop.sh [aws-region] [options]

Stops that region's bastion instance. Idempotent: a stop of an already-stopped
instance is reported and exits 0.

Arguments:
  [aws-region]            Region the bastion lives in (e.g. ap-southeast-2).
                          Defaults to ap-southeast-2.

Options:
  -i, --instance-id <id>  Target this instance instead of the one published at
                          /derrops/region/bastion/instance-id.
  -w, --wait              Block until the instance reaches 'stopped'. This is
                          the default; the flag is accepted for explicitness.
  -n, --no-wait           Return as soon as the stop is accepted, without
                          polling for 'stopped'.
  -h, --help              Show this help.

Examples:
  ./scripts/bastion-stop.sh ap-southeast-2
  ./scripts/bastion-stop.sh ap-southeast-2 --no-wait
EOF
}

die() {
  echo "error: $*" >&2
  exit 1
}

region=''
instance_id=''
# Waiting is the default: 'stop accepted' is not 'stopped', and the useful
# confirmation is that the instance actually got there. --no-wait opts out.
wait_for_state='true'

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    -i|--instance-id)
      [[ $# -ge 2 ]] || die "$1 needs a value"
      instance_id="$2"
      shift 2
      ;;
    -w|--wait)
      wait_for_state='true'
      shift
      ;;
    -n|--no-wait)
      wait_for_state='false'
      shift
      ;;
    -*)
      die "unknown option: $1"
      ;;
    *)
      [[ -z "$region" ]] || die "unexpected extra argument: $1"
      region="$1"
      shift
      ;;
  esac
done

if [[ -z "$region" ]]; then
  region="$DEFAULT_REGION"
  echo "No region given — defaulting to ${region}." >&2
fi

command -v aws >/dev/null 2>&1 || die 'aws CLI not found on PATH.'

# Resolve the target. Every call carries an explicit --region: the parameter
# name is the same in every region, so each read must say which one it means.
if [[ -z "$instance_id" ]]; then
  echo "Resolving bastion instance from ${PARAM_NAME} in ${region}..." >&2
  instance_id="$(aws ssm get-parameter \
    --region "$region" \
    --name "$PARAM_NAME" \
    --query Parameter.Value \
    --output text)" || die "could not read ${PARAM_NAME} in ${region}.
       Is derrops--region--bastion deployed there?
         npx cdk deploy --all -c region=${region}"
fi
[[ -n "$instance_id" && "$instance_id" != 'None' ]] || die \
  "no instance id at ${PARAM_NAME} in ${region}."

state="$(aws ec2 describe-instances \
  --region "$region" \
  --instance-ids "$instance_id" \
  --query 'Reservations[0].Instances[0].State.Name' \
  --output text)" || die "could not describe ${instance_id} in ${region}."

case "$state" in
  stopped)
    echo "${instance_id} (${region}) is already stopped."
    exit 0
    ;;
  stopping)
    echo "${instance_id} (${region}) is already stopping."
    ;;
  terminated|shutting-down)
    die "${instance_id} in ${region} is ${state} — it cannot be stopped or restarted.
       Redeploy the stack to get a new bastion:
         npx cdk deploy --all -c region=${region}"
    ;;
  *)
    echo "Stopping ${instance_id} (${region}, currently ${state})..." >&2
    aws ec2 stop-instances \
      --region "$region" \
      --instance-ids "$instance_id" \
      --query 'StoppingInstances[0].[InstanceId,PreviousState.Name,CurrentState.Name]' \
      --output text >/dev/null
    ;;
esac

if [[ "$wait_for_state" == 'true' ]]; then
  echo 'Waiting for state stopped...' >&2
  aws ec2 wait instance-stopped --region "$region" --instance-ids "$instance_id"
  echo "${instance_id} (${region}) is stopped."
else
  echo "Stop requested for ${instance_id} (${region}); it takes a minute or so to reach 'stopped'.
Check with:
  aws ec2 describe-instances --region ${region} --instance-ids ${instance_id} \\
    --query 'Reservations[0].Instances[0].State.Name' --output text"
fi
