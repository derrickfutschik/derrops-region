#!/usr/bin/env bash
#
# Start the region's bastion instance (the counterpart to bastion-stop.sh).
#
# Brings the same instance back — same id, same security group, same SSM
# parameter — so `bastion-session.sh` works again once its SSM agent has
# re-registered. Nothing is redeployed.
#
#   ./scripts/bastion-start.sh ap-southeast-2
#   ./scripts/bastion-start.sh ap-southeast-2 --no-wait
#
# By default it polls until the instance is running *and* its SSM agent is
# online, so a successful exit means `bastion-session.sh` will connect.
# `--no-wait` returns as soon as the start is accepted.
#
# The region defaults to ap-southeast-2 when omitted. Note that this differs
# from the `cdk` commands in this repo, which never default: the bastion's SSM
# parameter name is identical in every region, so an omitted region here starts
# ap-southeast-2's box rather than erroring. The script says so on stderr
# whenever it falls back.
#
# It also posts one power-on request to the bastion's CloudWatch metric, so the
# stack's alarm holds the box on and then stops it once the hold (4 hours by
# default) has passed with no further request — a box started here is not left
# running forever. To keep it up longer, post again, or suspend the stop with
# /derrops/region/bastion/auto-stop/enabled.
#
# Note: the instance gets a *new* auto-assigned public IPv4 on every start.
# Nothing here depends on it (SSM and Tailscale are both outbound-initiated),
# but do not pin anything to that address. Tailscale, if you brought it up
# manually, needs `sudo tailscale up ...` again unless you enabled its service.
#
# Requires: aws CLI v2.
set -euo pipefail

# Published by BastionStack — see lib/bastion-stack.ts ('ssmParam', key
# 'instance-id'). Generated by derrops-conventions; mirrored here because a
# shell script cannot call the library.
readonly PARAM_NAME='/derrops/region/bastion/instance-id'

# The power-on metric BastionStack's alarm watches — `powerMetric` in
# lib/bastion-stack.ts, also published at /derrops/region/bastion/power-metric.
# Mirrored here for the same reason as PARAM_NAME.
readonly METRIC_NAMESPACE='derrops/region'
readonly METRIC_NAME='PowerOnRequests'
readonly METRIC_DIMENSIONS='service=bastion'

# Region used when the caller omits one.
readonly DEFAULT_REGION='ap-southeast-2'

usage() {
  cat <<'EOF'
Usage: bastion-start.sh [aws-region] [options]

Starts that region's bastion instance. Idempotent: a start of an
already-running instance is reported and exits 0. Also posts a power-on
request, so the box is stopped again automatically once the stack's hold
(4 hours by default) passes with no further request.

Arguments:
  [aws-region]            Region the bastion lives in (e.g. ap-southeast-2).
                          Defaults to ap-southeast-2.

Options:
  -i, --instance-id <id>  Target this instance instead of the one published at
                          /derrops/region/bastion/instance-id.
  -w, --wait              Block until the instance is running *and* its SSM
                          agent has re-registered, i.e. until
                          bastion-session.sh will actually connect. This is the
                          default; the flag is accepted for explicitness.
  -n, --no-wait           Return as soon as the start is accepted, without
                          polling for 'running' or for the SSM agent.
  -h, --help              Show this help.

Examples:
  ./scripts/bastion-start.sh ap-southeast-2
  ./scripts/bastion-start.sh ap-southeast-2 --no-wait
EOF
}

die() {
  echo "error: $*" >&2
  exit 1
}

region=''
instance_id=''
# Waiting is the default: the useful end state is 'connectable', not 'start
# accepted'. --no-wait opts out.
wait_for_state='true'

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    -i|--instance-id)
      [[ $# -ge 2 ]] || die "$1 needs a value"
      instance_id="$2"
      shift 2
      ;;
    -w|--wait)
      wait_for_state='true'
      shift
      ;;
    -n|--no-wait)
      wait_for_state='false'
      shift
      ;;
    -*)
      die "unknown option: $1"
      ;;
    *)
      [[ -z "$region" ]] || die "unexpected extra argument: $1"
      region="$1"
      shift
      ;;
  esac
done

if [[ -z "$region" ]]; then
  region="$DEFAULT_REGION"
  echo "No region given — defaulting to ${region}." >&2
fi

command -v aws >/dev/null 2>&1 || die 'aws CLI not found on PATH.'

# Resolve the target. Every call carries an explicit --region: the parameter
# name is the same in every region, so each read must say which one it means.
if [[ -z "$instance_id" ]]; then
  echo "Resolving bastion instance from ${PARAM_NAME} in ${region}..." >&2
  instance_id="$(aws ssm get-parameter \
    --region "$region" \
    --name "$PARAM_NAME" \
    --query Parameter.Value \
    --output text)" || die "could not read ${PARAM_NAME} in ${region}.
       Is derrops--region--bastion deployed there?
         npx cdk deploy --all -c region=${region}"
fi
[[ -n "$instance_id" && "$instance_id" != 'None' ]] || die \
  "no instance id at ${PARAM_NAME} in ${region}."

state="$(aws ec2 describe-instances \
  --region "$region" \
  --instance-ids "$instance_id" \
  --query 'Reservations[0].Instances[0].State.Name' \
  --output text)" || die "could not describe ${instance_id} in ${region}."

case "$state" in
  running)
    echo "${instance_id} (${region}) is already running."
    ;;
  pending)
    echo "${instance_id} (${region}) is already starting."
    ;;
  terminated|shutting-down)
    die "${instance_id} in ${region} is ${state} — it cannot be started.
       Redeploy the stack to get a new bastion:
         npx cdk deploy --all -c region=${region}"
    ;;
  stopping)
    # start-instances is rejected mid-stop; wait it out rather than fail.
    echo "${instance_id} (${region}) is still stopping — waiting for it to settle..." >&2
    aws ec2 wait instance-stopped --region "$region" --instance-ids "$instance_id"
    echo "Starting ${instance_id} (${region})..." >&2
    aws ec2 start-instances \
      --region "$region" \
      --instance-ids "$instance_id" \
      --output text >/dev/null
    ;;
  *)
    echo "Starting ${instance_id} (${region}, currently ${state})..." >&2
    aws ec2 start-instances \
      --region "$region" \
      --instance-ids "$instance_id" \
      --output text >/dev/null
    ;;
esac

# Register the start with the power alarm. Without this the alarm never enters
# ALARM, so it never comes back to OK, and nothing would ever stop the box. Not
# fatal: the instance is already starting, so say what was lost and carry on.
aws cloudwatch put-metric-data \
  --region "$region" \
  --namespace "$METRIC_NAMESPACE" \
  --metric-name "$METRIC_NAME" \
  --dimensions "$METRIC_DIMENSIONS" \
  --value 1 \
  || echo "warning: could not post ${METRIC_NAMESPACE} ${METRIC_NAME} in ${region} — the bastion
         will NOT be stopped automatically. Stop it with bastion-stop.sh." >&2

if [[ "$wait_for_state" != 'true' ]]; then
  echo "Start requested for ${instance_id} (${region}). It takes a minute or two before
its SSM agent re-registers and a session can be opened:
  ./scripts/bastion-session.sh ${region}"
  exit 0
fi

echo 'Waiting for state running...' >&2
aws ec2 wait instance-running --region "$region" --instance-ids "$instance_id"

# 'running' is not 'connectable': Session Manager only accepts a target once the
# SSM agent has re-registered and is pinging. Wait for that too, so a --wait
# start is immediately followed by a working bastion-session.sh.
echo 'Waiting for the SSM agent to register...' >&2
for _ in $(seq 1 60); do
  ping_status="$(aws ssm describe-instance-information \
    --region "$region" \
    --filters "Key=InstanceIds,Values=${instance_id}" \
    --query 'InstanceInformationList[0].PingStatus' \
    --output text 2>/dev/null || true)"
  if [[ "$ping_status" == 'Online' ]]; then
    echo "${instance_id} (${region}) is running and online in SSM.
Connect with:
  ./scripts/bastion-session.sh ${region}"
    exit 0
  fi
  sleep 5
done

die "${instance_id} is running in ${region} but its SSM agent did not come online
       within 5 minutes (ping status: ${ping_status:-none}). Check that its
       instance profile grants AmazonSSMManagedInstanceCore and that the subnet
       still has a route out to the SSM endpoints."
