#!/usr/bin/env bash
#
# Open an interactive shell on the region's bastion over SSM Session Manager.
#
# This is the SSH replacement for `derrops--region--bastion`: the instance has
# no inbound rules and no key pair, so there is no sshd to reach. Session
# Manager tunnels a shell over the SSM agent's outbound HTTPS instead.
#
#   ./scripts/bastion-session.sh ap-southeast-2
#   ./scripts/bastion-session.sh ap-southeast-2 --user ssm-user
#
# The region defaults to ap-southeast-2 when omitted. Note that this differs
# from the `cdk` commands in this repo, which never default: the bastion's SSM
# parameter name is identical in every region, so an omitted region here lands
# you on ap-southeast-2's box rather than erroring. The script says so on stderr
# whenever it falls back.
#
# Requires: aws CLI v2 and the session-manager-plugin
#   https://docs.aws.amazon.com/systems-manager/latest/userguide/session-manager-working-with-install-plugin.html
#   (macOS: brew install --cask session-manager-plugin)
set -euo pipefail

# Published by BastionStack — see lib/bastion-stack.ts ('ssmParam', key
# 'instance-id'). Generated by derrops-conventions; mirrored here because a
# shell script cannot call the library.
readonly PARAM_NAME='/derrops/region/bastion/instance-id'

# Region used when the caller omits one.
readonly DEFAULT_REGION='ap-southeast-2'

usage() {
  cat <<'EOF'
Usage: bastion-session.sh [aws-region] [options]

Opens an interactive shell on that region's bastion via SSM Session Manager,
as ec2-user.

Arguments:
  [aws-region]            Region the bastion lives in (e.g. ap-southeast-2).
                          Defaults to ap-southeast-2.

Options:
  -i, --instance-id <id>  Target this instance instead of the one published at
                          /derrops/region/bastion/instance-id.
  -u, --user <name>       Land as this OS user instead of the default ec2-user.
                          Pass ssm-user for Session Manager's own account.
  -h, --help              Show this help.

Examples:
  ./scripts/bastion-session.sh ap-southeast-2
  ./scripts/bastion-session.sh ap-southeast-2 --user ssm-user
EOF
}

die() {
  echo "error: $*" >&2
  exit 1
}

region=''
instance_id=''
os_user='ec2-user'

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    -i|--instance-id)
      [[ $# -ge 2 ]] || die "$1 needs a value"
      instance_id="$2"
      shift 2
      ;;
    -u|--user)
      [[ $# -ge 2 ]] || die "$1 needs a value"
      os_user="$2"
      shift 2
      ;;
    -*)
      die "unknown option: $1"
      ;;
    *)
      [[ -z "$region" ]] || die "unexpected extra argument: $1"
      region="$1"
      shift
      ;;
  esac
done

if [[ -z "$region" ]]; then
  region="$DEFAULT_REGION"
  echo "No region given — defaulting to ${region}." >&2
fi

command -v aws >/dev/null 2>&1 || die 'aws CLI not found on PATH.'
command -v session-manager-plugin >/dev/null 2>&1 || die \
  'session-manager-plugin not found on PATH — start-session cannot run without it.
       Install it: brew install --cask session-manager-plugin'

# Resolve the target. Every call carries an explicit --region: the parameter
# name is the same in every region, so each read must say which one it means.
if [[ -z "$instance_id" ]]; then
  echo "Resolving bastion instance from ${PARAM_NAME} in ${region}..." >&2
  instance_id="$(aws ssm get-parameter \
    --region "$region" \
    --name "$PARAM_NAME" \
    --query Parameter.Value \
    --output text)" || die "could not read ${PARAM_NAME} in ${region}.
       Is derrops--region--bastion deployed there?
         npx cdk deploy --all -c region=${region}"
fi
[[ -n "$instance_id" && "$instance_id" != 'None' ]] || die \
  "no instance id at ${PARAM_NAME} in ${region}."

# Fail with a useful message rather than the plugin's opaque one: an instance
# only accepts sessions once its SSM agent has registered and is pinging.
ping_status="$(aws ssm describe-instance-information \
  --region "$region" \
  --filters "Key=InstanceIds,Values=${instance_id}" \
  --query 'InstanceInformationList[0].PingStatus' \
  --output text 2>/dev/null || true)"
if [[ "$ping_status" != 'Online' ]]; then
  die "${instance_id} is not registered with SSM in ${region} (ping status: ${ping_status:-none}).
       A freshly launched instance takes a minute or two to register. If it never
       does, check that its instance profile grants AmazonSSMManagedInstanceCore
       and that the subnet has a route out to the SSM endpoints."
fi

echo "Starting SSM session on ${instance_id} (${region})..." >&2

if [[ -n "$os_user" ]]; then
  # Session Manager drops you in as ssm-user; AWS-StartInteractiveCommand runs
  # a login shell as the user you asked for instead — ec2-user by default, so a
  # session here matches what SSH to an Amazon Linux box would have given you.
  exec aws ssm start-session \
    --region "$region" \
    --target "$instance_id" \
    --document-name AWS-StartInteractiveCommand \
    --parameters "command=[\"sudo -u ${os_user} -i\"]"
fi

exec aws ssm start-session --region "$region" --target "$instance_id"
